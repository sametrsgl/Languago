const fs = require('fs');
const path = require('path');

const SITE_DATA = "C:/Users/Samet Tıraşoğlu.DESKTOP-V1NEC06/synth-app/languago-platform/src/data";
const APP_ASSETS = "C:/Users/Samet Tıraşoğlu.DESKTOP-V1NEC06/synth-app/english-word-coach/android/app/src/main/assets";

// Readings files - just convert export const → window.X
const READING_FILES = [
  ['readings_a1.js', 'READINGS_A1'],
  ['readings_a2.js', 'READINGS_A2'],
  ['readings_b1.js', 'READINGS_B1'],
  ['readings_b2.js', 'READINGS_B2'],
  ['readings_c1.js', 'READINGS_C1'],
  ['readings_c2.js', 'READINGS_C2'],
  ['readings_ielts.js', 'READINGS_IELTS'],
  ['readings_toefl.js', 'READINGS_TOEFL'],
  ['readings_yds.js', 'READINGS_YDS'],
  ['readings_yokdil.js', 'READINGS_YOKDIL'],
  ['readings_gre.js', 'READINGS_GRE'],
];

for (const [file, constName] of READING_FILES) {
  const sitePath = path.join(SITE_DATA, file);
  if (!fs.existsSync(sitePath)) {
    console.log(`SKIP: ${file} not found`);
    continue;
  }
  
  let code = fs.readFileSync(sitePath, 'utf8');
  
  // Convert: export const NAME = → window.NAME =
  code = code.replace(/export\s+const\s+(\w+)\s*=/, 'window.$1 =');
  
  // Remove the AUTO-GENERATED header comments (keep original style)
  code = code.replace(/\/\/ AUTO-GENERATED by scripts\/port_content\.mjs[\s\S]*?:\/\/ Source: english-word-coach Android assets.*?\.\n/, '');
  
  const destPath = path.join(APP_ASSETS, file);
  fs.writeFileSync(destPath, code, 'utf8');
  
  // Count entries
  const entries = (code.match(/\{ id:/g) || []).length;
  console.log(`  ${file}: ${entries} entries`);
}

console.log('\n=== Readings sync complete ===');
