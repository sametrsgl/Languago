// Konuşma Çarkı (speaking wheel): the built-in speaking bank for kids.
// Oyun Parkı, ages 9-11 (YLE / MEB grades 3-6). Pure data, no DOM: 8
// categories × 4 levels × 6 prompts, plus 15 + 15 Would You Rather cards.
// Everything students read is English; `tr` is a short gloss for the teacher.
// Personal prompts use dream or fictional frames: nothing about homes,
// families, money, health or looks. Prompts stay within the Genç word caps
// (A1 4, A2 8, B1 14, B2 20) and starters within 5 words, emoji not counted.
// Ids come from the position in each list, so add prompts at the end of a
// list instead of inserting them (saved games keep their ids).

const LEVELS = ['a1', 'a2', 'b1', 'b2'];

// One speak item with the fixed fields filled in, in the canonical order.
function speak(id, p, level, cat) {
  const item = { id, type: 'speak', mode: p.mode, prompt: p.prompt, label: p.label, emoji: p.emoji };
  if (p.mode === 'wyr') Object.assign(item, { optA: p.optA, optB: p.optB });
  return Object.assign(item, {
    starters: p.starters.slice(), followUps: p.followUps, useful: p.useful,
    model: p.model, tr: p.tr, level, cat,
  });
}

function category(id, title, emoji, lists) {
  const prompts = {};
  for (const level of LEVELS) {
    prompts[level] = lists[level].map((p, i) => speak(`kids-${id}-${level}-${i + 1}`, p, level, id));
  }
  return { id, title, emoji, prompts };
}

// Would You Rather reason frames: A1/A2 give one reason; B1 adds an answer
// back ("But if you..."), B2 a concession ("Even though...").
const WYR_FRAMES = {
  a1: ["I'd rather... because...", 'I like... more.', '...is more fun.'],
  a2: ["I'd rather... because...", 'I like... more.', '...is more fun.'],
  b1: ["I'd rather... because...", "But if you..., you'd...", "I'd choose..., so..."],
  b2: ["I'd rather... because...", "But if you..., you'd...", "Even though..., I'd still..."],
};

function wyrList(band, list) {
  return list.map((p, i) => speak(`kids-wyr-${band}-${i + 1}`, { ...p, mode: 'wyr', starters: WYR_FRAMES[p.level] }, p.level, 'wyr'));
}

