// Konuşma Çarkı (speaking wheel): built-in speaking bank for adults (Stüdyo).
// Pure data, no DOM: 8 categories × 4 levels × 6 prompts, plus 15 + 15
// Would You Rather cards. Every card is a full `speak` item (core/pack.mjs).
// Everything students read is English; `tr` is a short hint for the teacher.
// Real-life topics only: no income, religion, politics or health details.
// Ids are stable slugs (adults-travel-a1-1, adults-wyr-b2-3), so keep the
// order when editing and add new cards at the end of a list.

const LEVELS = ['a1', 'a2', 'b1', 'b2'];

// One category: fills in id, type, level and cat for every card.
function category(id, title, emoji, prompts) {
  const out = {};
  for (const level of LEVELS) {
    out[level] = (prompts[level] || []).map((p, i) => ({ id: `adults-${id}-${level}-${i + 1}`, type: 'speak', ...p, level, cat: id }));
  }
  return { id, title, emoji, prompts: out };
}

// Reason frames on the Would You Rather screen: from B1 each side may answer
// back once ("But if you..."), B2 adds concession ("Even though...").
const WYR_STARTERS = {
  a1: ["I'd rather ... because ...", 'I like ...', 'It is more ...'],
  a2: ["I'd rather ... because ...", "I don't like ... because ...", 'Last time I ...'],
  b1: ["I'd rather ... because ...", "But if you ..., you'd ...", "That's why I'd choose ..."],
  b2: ["I'd rather ... because ...", "But if you ..., you'd ...", "Even though ..., I'd still ..."],
};

// Would You Rather cards: n counts per level, so ids read adults-wyr-a2-3.
function wyrCards(list) {
  const seen = {};
  return list.map((p) => {
    seen[p.level] = (seen[p.level] || 0) + 1;
    return { id: `adults-wyr-${p.level}-${seen[p.level]}`, type: 'speak', mode: 'wyr', ...p, starters: WYR_STARTERS[p.level].slice(), cat: 'wyr' };
  });
}

